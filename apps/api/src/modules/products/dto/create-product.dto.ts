import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsArray,
  IsBoolean,
  IsEnum,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  MaxLength,
  MinLength,
  ValidateNested,
} from 'class-validator';
import { FoodPreference } from '@prisma/client';
import { CreateProductVariantDto } from './create-product-variant.dto';

export class CreateProductDto {
  @ApiProperty({
    description: 'Category or subcategory UUID',
    example: 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11',
  })
  @IsUUID('4')
  categoryId!: string;

  @ApiPropertyOptional({
    description: 'Brand UUID (optional if brand is specified as text)',
    example: 'b0eebc99-9c0b-4ef8-bb6d-6bb9bd380a22',
  })
  @IsOptional()
  @IsUUID('4')
  brandId?: string;

  @ApiProperty({
    description: 'Master product title',
    example: 'Amul Taaza Homogenised Toned Milk',
  })
  @IsString()
  @MinLength(2)
  @MaxLength(200)
  name!: string;

  @ApiPropertyOptional({
    description: 'Unique product URL slug (autogenerated if omitted)',
    example: 'amul-taaza-toned-milk',
  })
  @IsOptional()
  @IsString()
  @Matches(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, {
    message: 'Slug must contain only lowercase alphanumeric characters and hyphens',
  })
  slug?: string;

  @ApiPropertyOptional({
    description: 'Short single-line description for product cards and search results',
    example: 'Fresh pasteurized toned milk with 3.0% fat content.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(300)
  shortDescription?: string;

  @ApiPropertyOptional({
    description: 'Detailed product description and benefits',
  })
  @IsOptional()
  @IsString()
  description?: string;

  @ApiPropertyOptional({
    description: 'Brand display name',
    example: 'Amul',
  })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  brand?: string;

  @ApiPropertyOptional({
    description: 'Food preference classification (VEG, NON_VEG, VEGAN, NA)',
    enum: FoodPreference,
    default: FoodPreference.NA,
  })
  @IsOptional()
  @IsEnum(FoodPreference)
  foodPreference?: FoodPreference;

  @ApiPropertyOptional({
    description: 'Country of Origin for regulatory compliance',
    default: 'India',
  })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  countryOfOrigin?: string;

  @ApiPropertyOptional({
    description: 'Manufacturer name, address, and license',
  })
  @IsOptional()
  @IsString()
  manufacturerDetails?: string;

  @ApiPropertyOptional({
    description: 'Packer name and facility address',
  })
  @IsOptional()
  @IsString()
  packerDetails?: string;

  @ApiPropertyOptional({
    description: 'Shelf life / expiry information (e.g. 180 Days, 2 Days refrigerated)',
  })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  shelfLife?: string;

  @ApiPropertyOptional({
    description:
      'Storage instructions (e.g. Store in a cool and dry place. Keep refrigerated after opening)',
  })
  @IsOptional()
  @IsString()
  storageInstructions?: string;

  @ApiPropertyOptional({
    description: 'Ingredients list',
  })
  @IsOptional()
  @IsString()
  ingredients?: string;

  @ApiPropertyOptional({
    description: 'Nutritional information per 100g/100ml (JSON)',
  })
  @IsOptional()
  nutritionalInfo?: Record<string, unknown>;

  @ApiPropertyOptional({
    description: 'Category-specific product specifications (JSON)',
  })
  @IsOptional()
  specifications?: Record<string, unknown>;

  @ApiPropertyOptional({
    description: 'Dynamic key-value attributes (JSON)',
  })
  @IsOptional()
  attributes?: Record<string, unknown>;

  @ApiPropertyOptional({
    description: 'Search keywords, synonyms, and localized terms (e.g. doodh, milk, toned)',
    type: [String],
  })
  @IsOptional()
  @IsArray()
  @IsString({ each: true })
  searchTags?: string[];

  @ApiPropertyOptional({
    description: 'Flag to feature on home carousels and highlight sections',
    default: false,
  })
  @IsOptional()
  @IsBoolean()
  isFeatured?: boolean;

  @ApiPropertyOptional({
    description: 'Initial variant to create atomically with the master product',
    type: CreateProductVariantDto,
  })
  @IsOptional()
  @ValidateNested()
  @Type(() => CreateProductVariantDto)
  initialVariant?: CreateProductVariantDto;
}
