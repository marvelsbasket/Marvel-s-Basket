import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsBoolean,
  IsInt,
  IsNumber,
  IsOptional,
  IsString,
  MaxLength,
  Min,
  MinLength,
} from 'class-validator';

export class CreateProductVariantDto {
  @ApiProperty({
    description: 'Variant title / pack identifier',
    example: '500 ml',
  })
  @IsString()
  @MinLength(1)
  @MaxLength(100)
  name!: string;

  @ApiPropertyOptional({
    description: 'Pack size descriptor for UI',
    example: '500 ml - Pouch',
  })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  packSize?: string;

  @ApiPropertyOptional({
    description: 'Numeric quantity value for price-per-unit sorting',
    example: 500,
  })
  @IsOptional()
  @Type(() => Number)
  @IsNumber()
  @Min(0)
  unitValue?: number;

  @ApiPropertyOptional({
    description: 'Standard unit of measure (e.g. g, kg, ml, L, piece, pack)',
    example: 'ml',
  })
  @IsOptional()
  @IsString()
  @MaxLength(20)
  unitType?: string;

  @ApiProperty({
    description: 'Maximum Retail Price (MRP) in INR',
    example: 33.0,
  })
  @Type(() => Number)
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0)
  mrp!: number;

  @ApiPropertyOptional({
    description: 'Unique internal SKU code (autogenerated if omitted)',
    example: 'MB-AMUL-TAZA-500ML',
  })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  sku?: string;

  @ApiPropertyOptional({
    description: 'Barcode / EAN / UPC standard code',
    example: '8901262010053',
  })
  @IsOptional()
  @IsString()
  @MaxLength(50)
  barcode?: string;

  @ApiPropertyOptional({
    description: 'Primary image URL for this specific variant',
  })
  @IsOptional()
  @IsString()
  primaryImageUrl?: string;

  @ApiPropertyOptional({
    description: 'Whether the variant is active',
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  isActive?: boolean;

  @ApiPropertyOptional({
    description: 'Display order priority among variants',
    default: 0,
  })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(0)
  displayOrder?: number;

  @ApiPropertyOptional({
    description: 'Flexible variant-specific attributes (JSON)',
  })
  @IsOptional()
  attributes?: Record<string, unknown>;
}
